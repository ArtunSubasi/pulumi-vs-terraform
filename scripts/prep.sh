#!/usr/bin/env bash
# Pre-cache everything the demo needs, so nothing is downloaded on stage.
#   1. one provider mirror for Terraform + OpenTofu, and a CLI config for offline `init`
#   2. `terraform init` in every Terraform project (using that mirror)
#   3. npm dependencies, Pulumi plugins and generated SDKs for every Pulumi project
#   4. the Pulumi "typescript" template + its npm deps, so showcase 01 works offline
# Needs network. Safe to re-run.
set -euo pipefail
source "$(dirname "$0")/lib.sh"

for t in terraform node npm pulumi; do
  command -v "$t" >/dev/null || die "'$t' not found on PATH"
done
HAVE_TOFU=1; command -v tofu >/dev/null || { HAVE_TOFU=0; warn "tofu not found — skipping OpenTofu examples"; }

mkdir -p "$PROVIDER_MIRROR"

# --- 1. Provider mirror ---------------------------------------------------------
# Only final/ is mirrored: live/ uses the same providers by construction.
log "Mirroring providers into $(rel "$PROVIDER_MIRROR")"
for p in $(VARIANTS=final tf_projects); do
  has_tf_code "$p" || continue
  # `get` first: `providers mirror` needs the (local) modules installed
  (cd "$p" && terraform get >/dev/null && terraform providers mirror "$PROVIDER_MIRROR" >/dev/null) \
    || die "mirror failed in $(rel "$p")"
  ok "$(rel "$p")"
done
if [ "$HAVE_TOFU" = 1 ]; then
  for p in $(VARIANTS=final tofu_projects); do
    (cd "$p" && tofu providers mirror "$PROVIDER_MIRROR" >/dev/null) || die "mirror failed in $(rel "$p")"
    ok "$(rel "$p") (tofu)"
  done
fi
cat > "$CLI_CONFIG" <<EOF
# Generated by scripts/prep.sh — offline provider installation for the demo.
# Used by terraform and tofu via TF_CLI_CONFIG_FILE (see scripts/env.sh).
provider_installation {
  filesystem_mirror {
    path = "$PROVIDER_MIRROR"
  }
}
EOF

use_mirror

# --- 2. init every project from the mirror --------------------------------------
log "terraform init (offline, from the mirror)"
for p in $(tf_projects); do
  case "$p" in */01-bootstrap/terraform/live) continue ;; esac   # init is the live demo there
  has_tf_code "$p" || continue
  (cd "$p" && terraform init -input=false -no-color >/dev/null) || die "init failed in $(rel "$p")"
  ok "$(rel "$p")"
done
# OpenTofu projects aren't init-ed here: with state encryption, `tofu init` already needs
# the passphrase (TF_VAR_state_passphrase). The mirror above is enough to init offline on stage.

# --- 3. Pulumi projects ---------------------------------------------------------
export PULUMI_SKIP_UPDATE_CHECK=true
log "Pulumi: npm ci + plugins + generated SDKs"
for p in $(pulumi_projects); do
  # Output only on failure (SDK generation is chatty)
  out="$(
    cd "$p" || exit 1
    # `pulumi install` generates sdks/ (for `packages:` in Pulumi.yaml), installs plugins
    # and runs the package manager. npm ci first keeps package-lock.json authoritative.
    # (&&-chained: errexit doesn't apply inside a subshell that is followed by ||)
    if [ -f package-lock.json ] && ! grep -q '"file:sdks/' package.json; then
      npm ci --no-audit --no-fund --loglevel=error >/dev/null && pulumi install --no-dependencies >/dev/null
    else
      pulumi install >/dev/null
    fi 2>&1
  )" || { echo "$out" >&2; die "pulumi install failed in $(rel "$p")"; }
  ok "$(rel "$p")"
done

# --- 4. Pulumi template + npm cache for showcase 01 ------------------------------
# Rehearse the 01 live flow once in a temp dir: caches the template (for
# `pulumi new typescript --offline`) and the template's npm deps (for `npm install --prefer-offline`).
log "Caching the Pulumi 'typescript' template and its npm dependencies"
tmp="$(mktemp -d)"
if pulumi new typescript --name template-cache --generate-only --yes --dir "$tmp/t" >/dev/null 2>&1; then
  (cd "$tmp/t" && npm install --no-audit --no-fund --loglevel=error >/dev/null \
     && npm install --no-audit --no-fund --loglevel=error @pulumi/random >/dev/null) \
    && ok "template + npm cache warmed" || warn "npm install of the template failed"
else
  warn "could not fetch the 'typescript' template by name. On stage, use the URL form:"
  warn "  pulumi new https://github.com/pulumi/templates/tree/master/typescript"
fi
rm -rf "$tmp"

log "Done. In every demo terminal:  source scripts/env.sh"
